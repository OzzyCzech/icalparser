<?php
declare(strict_types=1);

/**
 * Generates resources/timezones/windows.php, the map of Windows timezone names to IANA
 * timezones, from the CLDR windowsZones.xml (the "001" territory is the default zone).
 *
 * Usage: php bin/timezones.php [path or URL of windowsZones.xml]
 *
 * The hand-maintained resources/timezones/aliases.php (Outlook and Exchange display names)
 * is not changed; its targets are validated and updated when CLDR changes the zone of the
 * same Windows timezone.
 */

const SOURCE = 'https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml';
const TARGET = __DIR__ . '/../resources/timezones/windows.php';
const ALIASES = __DIR__ . '/../resources/timezones/aliases.php';

$source = $argv[1] ?? SOURCE;
$xml = @file_get_contents($source);
if ($xml === false) {
	fwrite(STDERR, "Cannot read $source\n");
	exit(1);
}
$document = new DOMDocument();
$document->loadXML($xml);

$map = [];
foreach ($document->getElementsByTagName('mapZone') as $zone) {
	if ($zone->getAttribute('territory') === '001') {
		$map[$zone->getAttribute('other')] = $zone->getAttribute('type');
	}
}
if (count($map) < 100) {
	fwrite(STDERR, "Unexpected content of $source\n");
	exit(1);
}
ksort($map, SORT_STRING | SORT_FLAG_CASE);

$invalid = array_filter($map, static fn(string $zone): bool => !isValid($zone));
if ($invalid !== []) {
	fwrite(STDERR, 'Unknown to this PHP version, check the timezone database: ' . implode(', ', $invalid) . "\n");
}

$previous = is_file(TARGET) ? require TARGET : [];
write(TARGET, $map, "Windows timezone names mapped to IANA timezones.\n * Generated by bin/timezones.php from CLDR windowsZones.xml, do not edit.");

// keep aliases pointing to the zone CLDR uses now
$aliases = require ALIASES;
$renamed = [];
foreach ($previous as $windows => $zone) {
	if (isset($map[$windows]) && $map[$windows] !== $zone) {
		$renamed[$zone] = $map[$windows];
	}
}
$changed = false;
foreach ($aliases as $name => $zone) {
	if (isset($renamed[$zone])) {
		$aliases[$name] = $renamed[$zone];
		$changed = true;
	}
	if (!isValid($aliases[$name])) {
		fwrite(STDERR, "Invalid alias target: $name => {$aliases[$name]}\n");
	}
}
if ($changed) {
	write(ALIASES, $aliases, "Timezone names used by Outlook, Exchange and other programs that are not in CLDR,\n * mapped to IANA timezones. Maintained by hand; bin/timezones.php updates renamed zones.");
}

printf("%d Windows timezones, %d changes, %d aliases\n", count($map), count(array_diff_assoc($map, $previous)) + count(array_diff_key($previous, $map)), count($aliases));

function isValid(string $zone): bool {
	try {
		new DateTimeZone($zone);
		return true;
	} catch (Exception) {
		return false;
	}
}

/**
 * @param array<string, string> $map
 */
function write(string $file, array $map, string $description): void {
	$lines = '';
	foreach ($map as $name => $zone) {
		$lines .= "\t" . var_export($name, true) . ' => ' . var_export($zone, true) . ",\n";
	}
	file_put_contents($file, "<?php\ndeclare(strict_types=1);\n\n/**\n * $description\n */\nreturn [\n$lines];\n");
}
